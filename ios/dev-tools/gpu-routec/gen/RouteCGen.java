/*
 * GPU Route C — facade generator.
 *
 * Reflects the REAL LWJGL 3.3.2 org.lwjgl.opengl.GL45C (which inherits the whole GL11C..GL45C chain) to emit a
 * single `GLALL` facade carrying the exact GL constants (with their real GL enum values) and method signatures
 * the base `gpu` plugin references. The version classes (GL11C..GL45C) + EXT extend GLALL so the plugin's
 * `import static org.lwjgl.opengl.GL33C.*` / `import static GL42C.glTexStorage3D` etc. all resolve against our
 * facade with NO change to the plugin. This validates the "unmodified plugin source" leg of Route C AND the
 * emitted GLALL doubles as the precise spec the iOS JNI GL bridge must implement (names + values + signatures).
 *
 * Output: GLALL.java (constants + method stubs). Support classes (GL/GLCapabilities/GLUtil/Callback/Configuration/
 * EXTTextureFilterAnisotropic/BufferUtils/AWTContext + the version-class shims) are hand-written alongside.
 */
import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

public class RouteCGen
{
	public static void main(String[] a) throws Exception
	{
		String constFile = a[0], methFile = a[1], outDir = a[2];
		Class<?> GL = Class.forName("org.lwjgl.opengl.GL45C");

		List<String> constNames = Files.readAllLines(Paths.get(constFile));
		List<String> methNames = Files.readAllLines(Paths.get(methFile));

		StringBuilder consts = new StringBuilder();
		List<String> unresolvedConst = new ArrayList<>();
		for (String c : constNames)
		{
			c = c.trim();
			if (c.isEmpty()) continue;
			try
			{
				Field f = GL.getField(c);
				if (f.getType() == int.class && Modifier.isStatic(f.getModifiers()))
				{
					consts.append("\tpublic static final int ").append(c)
						.append(" = ").append(f.getInt(null)).append(";\n");
				}
				else
				{
					unresolvedConst.add(c + " (non-int)");
				}
			}
			catch (NoSuchFieldException e)
			{
				unresolvedConst.add(c);
			}
		}

		StringBuilder meths = new StringBuilder();
		List<String> unresolvedMeth = new ArrayList<>();
		Set<String> emittedSigs = new LinkedHashSet<>();
		for (String m : methNames)
		{
			m = m.trim();
			if (m.isEmpty()) continue;
			boolean any = false;
			for (Method mm : GL.getMethods())
			{
				if (!mm.getName().equals(m) || !Modifier.isStatic(mm.getModifiers())) continue;
				String sig = signature(mm);
				if (emittedSigs.add(sig)) // dedupe identical erasures
				{
					meths.append(sig);
					any = true;
				}
				else
				{
					any = true;
				}
			}
			if (!any) unresolvedMeth.add(m);
		}

		StringBuilder out = new StringBuilder();
		out.append("// GENERATED by RouteCGen — DO NOT EDIT. Facade base for the base `gpu` plugin's LWJGL surface.\n");
		out.append("// Constants carry the REAL GL enum values (reflected from LWJGL 3.3.2 GL45C); method bodies are\n");
		out.append("// stubs (compile-only). This file is the iOS JNI GL bridge spec.\n");
		out.append("package org.lwjgl.opengl;\n\n");
		out.append("public class GLALL {\n");
		out.append(consts).append("\n").append(meths);
		out.append("}\n");
		Files.write(Paths.get(outDir, "GLALL.java"), out.toString().getBytes(StandardCharsets.UTF_8));

		try (PrintWriter pw = new PrintWriter(Files.newBufferedWriter(Paths.get(outDir, "UNRESOLVED.txt"))))
		{
			pw.println("# constants not found in GL45C (route to EXT/other facade):");
			for (String s : new TreeSet<>(unresolvedConst)) pw.println(s);
			pw.println("# methods not found in GL45C:");
			for (String s : new TreeSet<>(unresolvedMeth)) pw.println(s);
		}
		System.out.println("constants emitted=" + (constNames.size() - unresolvedConst.size())
			+ " unresolved=" + unresolvedConst.size());
		System.out.println("methods names=" + methNames.size() + " unresolved=" + unresolvedMeth.size()
			+ " sigs=" + emittedSigs.size());
		System.out.println("unresolved consts: " + unresolvedConst);
		System.out.println("unresolved meths: " + unresolvedMeth);
	}

	static String signature(Method m)
	{
		StringBuilder sb = new StringBuilder("\tpublic static ");
		sb.append(typeName(m.getReturnType())).append(" ").append(m.getName()).append("(");
		Class<?>[] ps = m.getParameterTypes();
		for (int i = 0; i < ps.length; i++)
		{
			if (i > 0) sb.append(", ");
			sb.append(typeName(ps[i])).append(" a").append(i);
		}
		sb.append(") { ").append(returnStub(m.getReturnType())).append(" }\n");
		return sb.toString();
	}

	static String typeName(Class<?> c)
	{
		if (c.isArray()) return typeName(c.getComponentType()) + "[]";
		return c.getCanonicalName();
	}

	static String returnStub(Class<?> r)
	{
		if (r == void.class) return "";
		if (r == boolean.class) return "return false;";
		if (r == int.class || r == short.class || r == byte.class || r == char.class
			|| r == long.class || r == float.class || r == double.class) return "return 0;";
		return "return null;";
	}
}
